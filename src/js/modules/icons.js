export function renderIcon(name) {
    const d = ICONS[name];
    if (!d) return '';
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', '18');
    svg.setAttribute('height', '18');
    svg.style.cssText = 'fill:currentColor;vertical-align:middle;display:inline-block;';
    const path = document.createElementNS(SVG_NS, 'path');
    path.setAttribute('d', d);
    svg.appendChild(path);
    return svg.outerHTML;
}

function replaceIcons(root) {
    (root.querySelectorAll ? root.querySelectorAll('.mat-icon:not(.icon-rendered)') : []).forEach((el) => {
        const name = el.textContent.trim();
        if (!name || !ICONS[name]) return;
        el.innerHTML = renderIcon(name);
        el.classList.add('icon-rendered');
    });
}

let observer = null;

export function initIcons() {
    replaceIcons(document);
    if (observer) return;
    observer = new MutationObserver((mutations) => {
        for (const m of mutations) {
            for (const node of m.addedNodes) {
                if (node.nodeType === 1) replaceIcons(node);
            }
        }
    });
    observer.observe(document.body, { childList: true, subtree: true });
}
